"""
suggestion_engine.py
--------------------
Produces SPECIFIC, actionable suggestions.

RULES:
  * Never include the user's password (or a long fragment of it).
  * Prefer actionable, educational language.
  * Always include general hygiene advice for weak passwords.
"""

from typing import Dict, List

GENERAL_HYGIENE = [
    "Use a unique password for every account — never reuse passwords.",
    "Use a password manager to generate and store unique passwords.",
    "Enable Multi-Factor Authentication (MFA) wherever it is available.",
    "Never share your password, and be cautious of phishing pages.",
    "Change your password immediately if you suspect a compromise.",
]


def generate_suggestions(
    findings: List[Dict],
    metrics: Dict,
    score: int,
    classification: str,
) -> List[str]:
    suggestions: List[str] = []
    seen_types = {f.get("type") for f in findings}

    # --- Pattern-specific advice -----------------------------------------
    if "common_password" in seen_types:
        suggestions.append(
            "This password matches a commonly used password pattern and should "
            "not be used. Choose something entirely different."
        )

    if "keyboard_pattern" in seen_types:
        suggestions.append(
            "Avoid keyboard sequences such as 'qwerty', 'asdf' or 'zxcv'. "
            "They are among the very first guesses attackers try."
        )

    if "sequence" in seen_types:
        suggestions.append(
            "Your password contains a predictable character sequence "
            "(for example 1234 or abcd). Replace it with unrelated characters."
        )

    if "repetition_chars" in seen_types or "repetition_substring" in seen_types:
        suggestions.append(
            "Your password repeats characters or blocks. Repetition adds length "
            "but almost no unpredictability."
        )

    if "predictable_structure" in seen_types:
        suggestions.append(
            "Adding a number to a common word (for example word + 123) does not "
            "create a strong password. Use unrelated, random words instead."
        )

    if "year_pattern" in seen_types:
        suggestions.append(
            "Avoid years such as birth years or the current year. Attackers "
            "try these first."
        )

    if "dictionary_word" in seen_types:
        suggestions.append(
            "Avoid dictionary words on their own. If you use words, combine "
            "several unrelated ones into a long passphrase."
        )

    if "personal_info" in seen_types:
        suggestions.append(
            "Avoid including your name, birth year, college or company name. "
            "This information is easy to find or guess."
        )

    # --- Length / diversity advice ---------------------------------------
    length = metrics.get("length", {}).get("length", 0)
    if length and length < 12:
        suggestions.append(
            "Consider using a longer password or passphrase. Length is one of "
            "the strongest contributors to password strength."
        )

    if metrics.get("characters", {}).get("character_type_count", 0) < 3:
        suggestions.append(
            "Increase character variety (lowercase, uppercase, numbers, symbols) "
            "— but remember that variety alone does not guarantee strength."
        )

    if metrics.get("characters", {}).get("unique_character_ratio", 1.0) < 0.6:
        suggestions.append(
            "Your password reuses the same characters a lot. Increase the number "
            "of distinct characters."
        )

    # --- Classification-based advice -------------------------------------
    if classification in ("VERY WEAK", "WEAK"):
        suggestions.append(
            "Consider a long passphrase of 4–6 randomly chosen, unrelated words, "
            "or a password generated by a password manager."
        )

    if not suggestions:
        suggestions.append(
            "Your password looks solid. Keep it unique to this account and "
            "store it in a password manager."
        )

    # --- Always-on hygiene reminders -------------------------------------
    for tip in GENERAL_HYGIENE[:3]:
        if tip not in suggestions:
            suggestions.append(tip)

    return suggestions